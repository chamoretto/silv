/// Names the shipped tables cover.
pub fn names() -> Vec<String> {
    LAYOUTS.iter().map(|(name, _)| (*name).to_owned()).collect()
}

/// Table text of a layout name.
pub fn table(name: &str) -> Option<&'static str> {
    LAYOUTS.iter().find(|(known, _)| *known == name).map(|(_, text)| *text)
}

/// Map of the layout the environment reports, empty when it names no shipped table.
pub fn active_map() -> KeyMap {
    let Some(name) = detected_layout().0 else {
        return KeyMap::raw();
    };
    let Some(text) = lookup(&name) else {
        return KeyMap::raw();
    };
    let (entries, _) = parse_table(text, &name);
    KeyMap::from_entries(entries, KeyMapOrigin::Layout(name))
}

/// One line description of the detection, for `--key-map-show`.
pub fn detail() -> String {
    match detected_layout() {
        (Some(name), source) if lookup(&name).is_some() => format!("layout `{name}` from {source}"),
        (Some(name), source) => format!("layout `{name}` from {source} has no shipped table"),
        (None, _) => "no layout in the environment, set XKB_DEFAULT_LAYOUT or use --key-map".to_owned(),
    }
}

/// Table of a detected name: the variant form first, then the plain layout name.
fn lookup(name: &str) -> Option<&'static str> {
    table(name).or_else(|| name.split(['-', ':']).next().and_then(table))
}

/// Layout name and the variable it came from; a list yields its first entry.
fn detected_layout() -> (Option<String>, &'static str) {
    for variable in ENV_LAYOUTS {
        let Some(value) = env::var_os(variable) else {
            continue;
        };
        let value = value.to_string_lossy();
        let first = value
            .split([',', ':'])
            .map(str::trim)
            .find(|entry| !entry.is_empty())
            .unwrap_or_default();
        if first.is_empty() {
            continue;
        }
        return (Some(normalize(first)), variable);
    }
    (None, "")
}

/// `setxkbmap` and locale forms of a layout, `us:dvorak` and `us(dvorak)`, to table names.
fn normalize(name: &str) -> String {
    let lowered = name
        .to_ascii_lowercase()
        .replace(['(', ')'], "-")
        .replace([':', '+'], "-");
    let mut out = String::new();
    for ch in lowered.chars() {
        let ch = if ch.is_whitespace() { '-' } else { ch };
        if ch != '-' || !out.ends_with('-') {
            out.push(ch);
        }
    }
    out.trim_matches('-').to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn variants_normalize_to_table_names() {
        assert_eq!(normalize("us:dvorak"), "us-dvorak");
        assert_eq!(normalize("US"), "us");
        assert_eq!(normalize("ru(phonetic_winkeys)"), "ru-phonetic_winkeys");
        assert_eq!(normalize("  de  "), "de");
    }

    #[test]
    fn lookup_falls_back_from_a_variant_to_the_layout() {
        assert!(lookup("us-dvorak").is_some());
        assert!(lookup("ru-phonetic_winkeys").is_some(), "variant falls back to ru");
        assert!(lookup("nosuchlayout").is_none());
    }

    #[test]
    fn names_are_unique_and_sorted_for_the_cli() {
        let mut names = names();
        let total = names.len();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), total);
        assert!(total > 30, "the shipped tables shrank: {total}");
    }
}
